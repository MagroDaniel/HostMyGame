import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { EventEmitter } from 'node:events';
import { save } from './store.js';
import { IS_WIN, expand, httpError, sleep, splitArgs } from './util.js';
import { startProcess } from './process.js';
import { getTemplate } from './catalog.js';
import { applyConfigWrite } from './configfiles.js';
import { LogTail } from './logtail.js';
import { Rcon, TelnetConsole, a2sInfo, bedrockPing, minecraftPing } from './protocols.js';
import { resolveJava } from './providers/java.js';
import { appInfo, installApp, installedBuild, windowsLaunch } from './providers/steamcmd.js';
import { installMinecraft, minecraftLaunchArgs } from './providers/minecraft.js';
import { installDownload } from './providers/download.js';
import { detectIssues, listIssues } from './issues.js';

const LOG_LIMIT = 2000;
const HISTORY_LIMIT = 180; // 6 minutes at one sample every 2s
const CRASH_WINDOW_MS = 5 * 60 * 1000;
const MAX_CRASH_RESTARTS = 3;

// Fields of a template that can be overridden per instance in the "Avançado" tab.
export const OVERRIDABLE = ['exe', 'args', 'stopCommands', 'console', 'ready', 'logFile', 'rconPort', 'rconPassword', 'queryType', 'queryPort', 'pty'];

export class Instance extends EventEmitter {
  constructor(cfg) {
    super();
    this.cfg = cfg;
    this.state = 'Stopped';
    this.issues = new Map(); // problems recognized in the console (see issues.js)
    this.proc = null;
    this.installProc = null;
    this.stopping = false;
    this.startedAt = null;
    this.log = [];
    this.history = [];
    this.players = new Set();
    this.queryInfo = null;
    this.metrics = { cpu: 0, mem: 0 };
    this.crashes = [];
    this.channel = null; // rcon/telnet connection
    fs.mkdirSync(this.dir, { recursive: true });
  }

  get template() { return getTemplate(this.cfg.templateId) || getTemplate('generic'); }
  get dir() { return this.cfg.dir; }
  get busy() { return !['Stopped', 'Failed'].includes(this.state); }
  get running() { return Boolean(this.proc); }

  // ---------- configuration helpers ----------
  settingDef(key) { return this.template.settings.find(s => s.key === key); }

  // Value of a placeholder as it should appear in a command line or config file.
  value(key) {
    if (key === 'dir') return this.dir;
    if (key === 'name') return this.cfg.name;
    if (key === 'java') return this.javaExe || 'java';
    const def = this.settingDef(key);
    const v = this.cfg.settings?.[key] ?? def?.default;
    if (!def) return v;
    if (def.type === 'bool') return def.arg ? (v ? def.arg : '') : (v ? (def.on ?? '1') : (def.off ?? '0'));
    if (def.arg) return v === '' || v == null ? '' : def.arg.replaceAll('{value}', v);
    return v;
  }

  expand(str) { return expand(str, k => this.value(k)); }

  effective(key) {
    const o = this.cfg.overrides || {};
    if (o[key] !== undefined && o[key] !== '') return o[key];
    const t = this.template;
    switch (key) {
      case 'stopCommands': return (t.stop?.commands || []).join('\n');
      case 'ready': return t.ready || '';
      case 'rconPort': return t.rcon?.port || '';
      case 'rconPassword': return t.rcon?.password || '';
      case 'queryType': return t.query?.type || '';
      case 'queryPort': return t.query?.port || '';
      default: return t[key] ?? '';
    }
  }

  get steamAppId() { return this.cfg.steamAppId || this.template.steam?.appId; }

  ports() {
    return this.template.ports
      .map(p => ({ name: p.name, port: Number(this.expand(p.port)), proto: p.proto }))
      .filter(p => p.port > 0 && p.port < 65536);
  }

  exePath() {
    const exe = this.expand(this.effective('exe'));
    if (!exe) return '';
    if (path.isAbsolute(exe)) return exe;
    const local = path.resolve(this.dir, exe);
    return fs.existsSync(local) || exe.includes('/') || exe.includes('\\') ? local : exe; // bare names come from PATH
  }

  isInstalled() {
    const t = this.template;
    if (t.provider === 'generic') return Boolean(this.effective('exe'));
    if (t.provider === 'minecraft' && t.flavor !== 'bedrock') {
      if (!this.cfg.installed) return false;
      return ['forge', 'neoforge'].includes(t.flavor)
        ? fs.existsSync(path.join(this.dir, 'libraries'))
        : fs.existsSync(path.join(this.dir, 'server.jar'));
    }
    const rawExe = this.effective('exe');
    if (!rawExe) return false;
    if (rawExe.includes('{{java}}')) return Boolean(this.cfg.installed);
    // hmg-start.bat is generated by prepare(), so check the game's own launcher instead.
    if (t.prepare === 'pz-wrapper' && !this.cfg.overrides?.exe) return fs.existsSync(path.join(this.dir, 'StartServer64.bat'));
    return fs.existsSync(path.resolve(this.dir, this.expand(rawExe)));
  }

  // ---------- console ----------
  print(text, source = 'server') {
    // Terminal color codes (e.g. Purpur's banner) would show up as "[38;5;14m" in the web console.
    text = String(text).replace(/\x1b\[[0-9;?]*[A-Za-z]/g, '');
    const entry = { t: Date.now(), source, text };
    if (source !== 'user') detectIssues(this, text);
    // Progress output ("Loading 41%", "Loading 42%"...) updates the previous line instead of piling up.
    const last = this.log.at(-1);
    if (last && last.source === source && entry.t - last.t < 3000 && /\d\s*%|progress:/i.test(text)
      && last.text.replace(/\d+/g, '#') === text.replace(/\d+/g, '#')) {
      this.log[this.log.length - 1] = entry;
      this.emit('console', { ...entry, replace: true });
      return;
    }
    this.log.push(entry);
    if (this.log.length > LOG_LIMIT) this.log.shift();
    this.emit('console', entry);
  }

  setState(state) {
    if (this.state === state) return;
    if (this.state === 'Installing') this.diskStale = true; // re-measure the folder after an install/update
    this.state = state;
    this.emit('state', state);
  }

  onLine(line) {
    this.print(line);
    if (this.state === 'Starting' && this.readyRe?.test(line)) this.onReady();
    const countRe = this.template.playerCountLog;
    if (countRe) {
      const m = line.match(new RegExp(countRe));
      if (m) this.logCount = Number(m[1]);
    }
    const pl = this.template.playerLog;
    if (pl) {
      const join = line.match(new RegExp(pl.join));
      const leave = line.match(new RegExp(pl.leave));
      if (join) this.players.add(join[1].trim());
      if (leave) this.players.delete(leave[1].trim());
    }
  }

  async onReady() {
    this.setState('Running');
    for (const cmd of this.template.startupCommands || []) {
      await sleep(500);
      try { await this.sendCommand(this.expand(cmd), 'panel'); } catch (e) { this.print(e.message, 'panel'); }
    }
  }

  // ---------- install ----------
  async install() {
    if (this.busy) throw httpError(409, 'Pare o servidor antes de instalar ou atualizar');
    const t = this.template;
    if (t.provider === 'generic') throw httpError(400, 'Programas personalizados não têm instalação automática');
    this.issues.clear();
    this.setState('Installing');
    const log = line => this.print(line, t.provider === 'steamcmd' ? 'steamcmd' : 'panel');
    try {
      let installed = {};
      if (t.provider === 'steamcmd') {
        if (!this.steamAppId) throw httpError(400, 'Informe o Steam App ID em Avançado');
        this.print(`Instalando App ${this.steamAppId} pelo SteamCMD...`, 'panel');
        await installApp({
          dir: this.dir, appId: this.steamAppId, login: t.steam?.login, branch: this.cfg.steamBranch,
          betaPassword: this.cfg.steamBetaPassword, log, onSpawn: child => { this.installProc = child; },
        });
        installed.build = installedBuild(this.dir, this.steamAppId);
        if (!this.effective('exe')) await this.detectLaunch();
      } else if (t.provider === 'minecraft') {
        installed = await installMinecraft(this, log);
      } else if (t.provider === 'download') {
        installed = await installDownload(this, log);
      }
      this.writeInitialFiles();
      this.cfg.installed = { ...installed, at: Date.now() };
      this.cfg.updateAvailable = false;
      save();
      this.print('Instalação concluída.', 'panel');
    } finally {
      this.installProc = null;
      this.setState('Stopped');
    }
  }

  async detectLaunch() {
    const info = (await appInfo([this.steamAppId]))[this.steamAppId];
    const launch = windowsLaunch(info);
    if (!launch) {
      this.print('Não foi possível detectar o executável. Configure em Avançado.', 'panel');
      return;
    }
    this.cfg.overrides = { ...this.cfg.overrides, exe: launch.exe, args: launch.args };
    this.print(`Executável detectado: ${launch.exe} ${launch.args}`, 'panel');
  }

  writeInitialFiles() {
    for (const f of this.template.initialFiles) {
      const file = path.join(this.dir, this.expand(f.path));
      if (fs.existsSync(file)) continue;
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, f.content);
    }
  }

  // ---------- start ----------
  // Writes settings into config files and prepares anything the launch needs.
  async prepare() {
    const t = this.template;
    fs.mkdirSync(path.join(this.dir, 'logs'), { recursive: true });
    this.writeInitialFiles();
    for (const entry of t.configWrites) {
      const values = {};
      for (const [k, tpl] of Object.entries(entry.values)) {
        const single = tpl.match(/^\{\{(\w+)\}\}$/);
        const def = single && this.settingDef(single[1]);
        const v = this.expand(tpl);
        values[k] = entry.format === 'json' && def && ['number', 'port'].includes(def.type) ? Number(v) : v;
      }
      const written = applyConfigWrite(this.dir, { ...entry, path: this.expand(entry.path) }, values);
      if (!written) this.print(`${this.expand(entry.path)} ainda não existe; as configurações serão aplicadas depois que o jogo criar o arquivo.`, 'panel');
    }
    if (t.prepare === 'pz-wrapper') this.writeZomboidWrapper();
    const usesJava = (t.provider === 'minecraft' && t.flavor !== 'bedrock') || /\{\{java\}\}/.test(this.effective('exe'));
    if (usesJava) {
      this.javaExe = await resolveJava(this.cfg.settings.javaPath, this.cfg.installed?.requiredJava || t.javaMajor, l => this.print(l, 'panel'));
    }
  }

  // Project Zomboid's StartServer64.bat only forwards two arguments and pauses at the end.
  writeZomboidWrapper() {
    const src = path.join(this.dir, 'StartServer64.bat');
    if (!fs.existsSync(src)) return;
    const mem = this.cfg.settings.memoryMb || 4096;
    const text = fs.readFileSync(src, 'utf8')
      .replace(/^\s*PAUSE\s*$/gim, '')
      .replace(/%1 %2/g, '%*')
      .replace(/-Xms\S+/g, `-Xms${mem}m`)
      .replace(/-Xmx\S+/g, `-Xmx${mem}m`);
    fs.writeFileSync(path.join(this.dir, 'hmg-start.bat'), text);
  }

  async launchCommand() {
    const t = this.template;
    const override = this.cfg.overrides?.args;
    if (t.provider === 'minecraft' && t.flavor !== 'bedrock') {
      return { cmd: this.javaExe, args: override ? splitArgs(this.expand(override)) : minecraftLaunchArgs(this) };
    }
    const cmd = this.exePath();
    if (!cmd) throw httpError(400, 'Executável não definido. Configure em Avançado.');
    return { cmd, args: splitArgs(this.expand(this.effective('args'))) };
  }

  async start({ skipUpdate = false } = {}) {
    if (this.busy) throw httpError(409, 'O servidor já está em execução');
    if (this.cfg.updateOnStart && !skipUpdate && this.template.provider !== 'generic') {
      this.print('Atualizando antes de iniciar...', 'panel');
      await this.install();
    }
    if (!this.isInstalled()) throw httpError(400, 'Servidor não instalado. Clique em "Instalar".');
    this.issues.clear();
    this.setState('Starting');
    try {
      await this.prepare();
      const { cmd, args } = await this.launchCommand();
      await this.spawnServer(cmd, args);
    } catch (e) {
      this.print(`Falha ao iniciar: ${e.message}`, 'panel');
      this.setState('Failed');
      throw e;
    }
  }

  usesPty() {
    const o = this.cfg.overrides?.pty;
    return o !== undefined && o !== '' ? o === 'true' : Boolean(this.template.pty);
  }

  async spawnServer(cmd, args) {
    const t = this.template;
    const cwd = t.cwd ? path.join(this.dir, t.cwd) : this.dir;
    const env = { ...process.env, ...t.env };
    this.stopping = false;
    this.players.clear();
    this.queryInfo = null;
    this.logCount = null;
    const ready = this.effective('ready');
    this.readyRe = ready ? new RegExp(ready) : null;
    const pty = this.usesPty();
    this.print(`Iniciando${pty ? ' (pseudoconsole)' : ''}: ${cmd} ${args.join(' ')}`, 'panel');

    const proc = await startProcess(cmd, args, { cwd, env, pty });
    this.proc = proc;
    this.startedAt = Date.now();
    // Remembered so a leftover server can be cleaned up if the panel itself crashes.
    this.cfg.pid = { pid: proc.pid, image: path.basename(pty && /\.(bat|cmd)$/i.test(cmd) ? 'cmd.exe' : cmd) };
    save();
    proc.on('line', line => {
      // A pseudo console echoes what we type; the command is already shown as "> ...".
      if (pty && this.lastSent && line.trim().endsWith(this.lastSent) && Date.now() - this.lastSentAt < 3000) { this.lastSent = null; return; }
      this.onLine(line);
    });
    proc.on('exit', code => this.onExit(proc, code));

    const logFile = this.expand(this.effective('logFile'));
    if (logFile) this.tail = new LogTail(path.resolve(this.dir, logFile), line => this.onLine(line));
    if (['rcon', 'telnet'].includes(this.effective('console'))) this.connectChannel(proc);
    if (!this.readyRe) this.onReady();
  }

  // Keeps trying to open the RCON/telnet console while the server boots.
  async connectChannel(proc) {
    const mode = this.effective('console');
    while (this.proc === proc && !this.stopping) {
      try {
        if (mode === 'rcon') {
          const rcon = new Rcon(this.expand(this.effective('rconPort')), this.expand(this.effective('rconPassword')));
          await rcon.connect();
          this.channel = rcon;
        } else {
          const t = this.template.telnet;
          const telnet = new TelnetConsole(this.expand(t.port), this.expand(t.password));
          await telnet.connect();
          telnet.on('line', line => this.onLine(line));
          telnet.on('close', () => { if (this.channel === telnet) this.channel = null; if (this.proc === proc && !this.stopping) setTimeout(() => this.connectChannel(proc), 5000); });
          this.channel = telnet;
        }
        this.print(`Console ${mode.toUpperCase()} conectado.`, 'panel');
        if (this.state === 'Starting' && !this.readyRe) this.onReady();
        return;
      } catch (e) {
        if (/senha recusada/.test(e.message)) {
          this.print(`${e.message}. Verifique a senha nas configurações.`, 'panel');
          return;
        }
        await sleep(5000);
      }
    }
  }

  onExit(proc, code) {
    if (this.proc !== proc) return;
    this.proc = null;
    delete this.cfg.pid;
    save();
    this.tail?.close();
    this.tail = null;
    this.channel?.close();
    this.channel = null;
    this.metrics = { cpu: 0, mem: 0 };
    this.players.clear();
    this.queryInfo = null;
    const expected = this.stopping || code === 0;
    this.print(`Processo encerrado (código ${code ?? '?'})`, 'panel');
    if (expected) return this.setState('Stopped');

    this.setState('Failed');
    if (!this.cfg.autoRestart) return;
    const now = Date.now();
    this.crashes = this.crashes.filter(t => now - t < CRASH_WINDOW_MS).concat(now);
    if (this.crashes.length > MAX_CRASH_RESTARTS) {
      this.print('O servidor travou várias vezes seguidas; reinício automático suspenso.', 'panel');
      return;
    }
    this.print('Travamento detectado, reiniciando em 5 segundos...', 'panel');
    setTimeout(() => {
      if (this.state !== 'Failed') return;
      this.start({ skipUpdate: true }).catch(e => this.print(`Reinício automático falhou: ${e.message}`, 'panel'));
    }, 5000);
  }

  // ---------- commands ----------
  async sendCommand(text, source = 'user') {
    if (this.state === 'Installing' && this.installProc) { // e.g. a Steam Guard code
      this.print('> ********', source);
      this.installProc.stdin.write(text + '\n');
      return;
    }
    if (!this.proc) throw httpError(409, 'O servidor não está em execução');
    const mode = this.effective('console');
    this.print(`> ${text}`, source);
    if (mode === 'stdin') {
      this.lastSent = text;
      this.lastSentAt = Date.now();
      return void this.proc.write(text);
    }
    if (mode === 'log') throw httpError(400, 'Este servidor não aceita comandos pelo painel (sem console/RCON).');
    if (!this.channel?.connected) throw httpError(409, `Console ${mode.toUpperCase()} ainda não conectado. Aguarde o servidor terminar de iniciar.`);
    if (mode === 'telnet') return void this.channel.send(text);
    const reply = await this.channel.send(text);
    for (const line of reply.split(/\r?\n/)) if (line.trim()) this.print(line, 'rcon');
  }

  // Sends a command and collects the server's console lines for a moment (e.g. the reply to "players").
  async commandOutput(text, ms = 1500) {
    const lines = [];
    const onEntry = e => { if (e.source !== 'user') lines.push(e.text); };
    this.on('console', onEntry);
    try {
      await this.sendCommand(text, 'panel');
      await sleep(ms);
    } finally {
      this.off('console', onEntry);
    }
    return lines;
  }

  canSendCommands() {
    const mode = this.effective('console');
    return mode === 'stdin' || (['rcon', 'telnet'].includes(mode) && Boolean(this.channel?.connected));
  }

  async stop() {
    const proc = this.proc;
    if (!proc) return;
    this.stopping = true;
    this.setState('Stopping');
    const exited = new Promise(resolve => proc.once('exit', resolve));
    const commands = this.effective('stopCommands').split(/\r?\n/).map(c => this.expand(c.trim())).filter(Boolean);
    if (commands.length && this.canSendCommands()) {
      for (const cmd of commands) {
        try { await this.sendCommand(cmd, 'panel'); } catch (e) { this.print(e.message, 'panel'); }
        await sleep(1000);
      }
    } else if (!IS_WIN) {
      proc.signal('SIGTERM');
    } else {
      this.kill();
    }
    const timer = setTimeout(() => {
      this.print('Tempo esgotado, forçando o encerramento...', 'panel');
      this.kill();
    }, (this.cfg.stopTimeoutSec || 60) * 1000);
    await exited;
    clearTimeout(timer);
  }

  kill() {
    const target = this.proc || this.installProc;
    if (!target) return;
    this.stopping = true;
    // taskkill /T also ends child processes, which many dedicated servers spawn.
    if (IS_WIN) spawn('taskkill', ['/PID', String(target.pid), '/T', '/F'], { windowsHide: true });
    else if (target.signal) target.signal('SIGKILL');
    else target.kill('SIGKILL');
  }

  async restart() {
    await this.stop();
    await this.start({ skipUpdate: false });
  }

  // ---------- players / status ----------
  async query() {
    if (this.state !== 'Running') return;
    const type = this.effective('queryType');
    const port = this.expand(this.effective('queryPort'));
    try {
      if (type === 'a2s') this.queryInfo = await a2sInfo(port);
      else if (type === 'minecraft') this.queryInfo = await minecraftPing(port);
      else if (type === 'bedrock') this.queryInfo = await bedrockPing(port);
      else if (type === 'rcon-palworld' && this.channel?.connected) {
        const reply = await this.channel.send('ShowPlayers');
        const names = reply.split(/\r?\n/).slice(1).map(l => l.split(',')[0]).filter(Boolean);
        this.queryInfo = { players: names.length, playerNames: names };
      }
    } catch {
      this.queryInfo = null;
    }
  }

  pushHistory(t) {
    this.history.push({ t, cpu: this.metrics.cpu, mem: this.metrics.mem, players: this.playerCount() });
    if (this.history.length > HISTORY_LIMIT) this.history.shift();
  }

  playerCount() {
    if (this.queryInfo?.players !== undefined) return this.queryInfo.players;
    if (this.template.playerLog) return this.players.size;
    if (this.template.playerCountLog && this.running) return this.logCount ?? 0;
    return null;
  }

  status() {
    const t = this.template;
    const names = this.queryInfo?.playerNames?.length ? this.queryInfo.playerNames : [...this.players];
    return {
      id: this.cfg.id,
      name: this.cfg.name,
      description: this.cfg.description || '',
      templateId: this.cfg.templateId,
      game: t.name,
      image: t.image,
      provider: t.provider,
      state: this.state,
      installed: this.isInstalled(),
      installedInfo: this.cfg.installed || null,
      updateAvailable: Boolean(this.cfg.updateAvailable),
      autoStart: Boolean(this.cfg.autoStart),
      cpu: this.metrics.cpu,
      mem: this.metrics.mem,
      disk: this.diskSize ?? null,
      memLimit: Number(this.cfg.settings?.memoryMb) * 1024 * 1024 || null,
      players: this.playerCount(),
      maxPlayers: this.queryInfo?.maxPlayers ?? (Number(this.cfg.settings?.maxPlayers) || null),
      playerNames: names,
      serverInfo: this.queryInfo ? { name: this.queryInfo.name, map: this.queryInfo.map, version: this.queryInfo.version } : null,
      uptime: this.proc ? Date.now() - this.startedAt : 0,
      ports: this.ports(),
      console: this.effective('console'),
      issues: listIssues(this),
      consoleReady: this.canSendCommands() || (this.state === 'Installing' && Boolean(this.installProc)),
    };
  }
}
